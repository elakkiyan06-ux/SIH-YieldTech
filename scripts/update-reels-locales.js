const LANGS = ['en', 'ta', 'hi', 'te', 'kn', 'ml'];
const DIRS = [
  path.resolve('./src/context/locales'),
  path.resolve('./SIH/src/context/locales')
];

for (const dir of DIRS) {
  const dicts = {};
  for (const lang of LANGS) {
    const jsonPath = path.join(dir, `${lang}.json`);
    dicts[lang] = fs.existsSync(jsonPath) ? JSON.parse(fs.readFileSync(jsonPath, 'utf8')) : {};
    
    // Update with new translations
    for (const [key, langMap] of Object.entries(REELS_TRANSLATIONS)) {
      dicts[lang][key] = langMap[lang] || langMap.en;
    }
  }

  // Ensure full key parity across all languages
  const allKeys = new Set();
  for (const lang of LANGS) {
    Object.keys(dicts[lang]).forEach(k => allKeys.add(k));
  }

  for (const key of allKeys) {
    const fallback = dicts['en'][key] || dicts['ta'][key] || key;
    for (const lang of LANGS) {
      if (!dicts[lang][key]) {
        dicts[lang][key] = fallback;
      }
    }
  }

  for (const lang of LANGS) {
    const jsonPath = path.join(dir, `${lang}.json`);
    const jsPath = path.join(dir, `${lang}.js`);

    // Write back JSON
    fs.writeFileSync(jsonPath, JSON.stringify(dicts[lang], null, 2), 'utf8');

    // Write back JS with both named and default export
    const jsContent = `export const ${lang} = ${JSON.stringify(dicts[lang], null, 2)};\nexport default ${lang};\n`;
    fs.writeFileSync(jsPath, jsContent, 'utf8');
  }
}

