const languages = ['en', 'ta', 'hi', 'te', 'kn', 'ml'];
const baseDir = path.resolve('src/context/locales');
const sihBaseDir = path.resolve('SIH/src/context/locales');

fs.mkdirSync(baseDir, { recursive: true });
fs.mkdirSync(sihBaseDir, { recursive: true });

// Read existing json files as base
const dicts = {};
for (const lang of languages) {
  const jsonPath = path.join(baseDir, `${lang}.json`);
  dicts[lang] = fs.existsSync(jsonPath) ? JSON.parse(fs.readFileSync(jsonPath, 'utf8')) : {};
}

// 1. Merge masterTranslations
for (const [key, map] of Object.entries(masterTranslations)) {
  for (const lang of languages) {
    dicts[lang][key] = map[lang] || map['en'] || key;
  }
}

// 2. Merge Indian States & Districts
for (const [key, map] of Object.entries(indianEntities)) {
  for (const lang of languages) {
    dicts[lang][key] = map[lang] || map['en'] || key;
  }
}

// 3. Ensure full parity: any key in any language is available in all languages (with en fallback)
const allKeys = new Set();
for (const lang of languages) {
  Object.keys(dicts[lang]).forEach(k => allKeys.add(k));
}

for (const key of allKeys) {
  const fallback = dicts['en'][key] || dicts['ta'][key] || key;
  for (const lang of languages) {
    if (!dicts[lang][key]) {
      dicts[lang][key] = fallback;
    }
  }
}

// 4. Save each locale as ES module
for (const lang of languages) {
  const jsContent = `// Farmogram AI Dictionary - ${lang.toUpperCase()}\nexport const ${lang} = ${JSON.stringify(dicts[lang], null, 2)};\n`;
  fs.writeFileSync(path.join(baseDir, `${lang}.js`), jsContent, 'utf8');
  fs.writeFileSync(path.join(sihBaseDir, `${lang}.js`), jsContent, 'utf8');
  console.log(`Successfully generated and synchronized ${lang}.js with ${Object.keys(dicts[lang]).length} keys.`);
}

console.log('Done! All 6 languages are now 100% key-synchronized.');
